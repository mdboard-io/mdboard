# Write RELEASE from VERSION and TAG. The release branch CI runs this on every merge.
set -Eeuo pipefail

root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
version_file="$root/VERSION"
tag_file="$root/TAG"
out="$root/RELEASE"

[ -r "$version_file" ] || { echo "ERROR: missing VERSION" >&2; exit 1; }
[ -r "$tag_file" ] || { echo "ERROR: missing TAG" >&2; exit 1; }
version="$(<"$version_file")"; version="${version//$'\r'/}"
tag="$(<"$tag_file")"; tag="${tag//$'\r'/}"
[[ "$version" =~ ^[0-9]+[.][0-9]+[.][0-9]+$ ]] || {
    echo "ERROR: invalid VERSION '$version'; expected MAJOR.MINOR.PATCH" >&2
    exit 1
}
[[ "$tag" =~ ^[A-Za-z0-9._-]*$ ]] || {
    echo "ERROR: invalid TAG '$tag'" >&2
    exit 1
}
tmp="$(mktemp "${out}.tmp.XXXXXX")"
trap 'rm -f -- "$tmp"' EXIT
printf '# Generated by sbin/makerelease.sh. Do not edit by hand.\nversion = "%s"\ntag = "%s"\n' \
    "$version" "$tag" >"$tmp"
chmod 0644 "$tmp"
mv -- "$tmp" "$out"
trap - EXIT
printf 'RELEASE: %s (tag %s)\n' "$version" "${tag:-release}"
