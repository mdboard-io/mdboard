//! Generated Markdown views for the 1.0 process model.

use std::path::Path;

use mdboard_core::process::{Meeting, Policy, ProcessCard, State, UpstreamRecord};

use crate::RenderPlan;

const GENERATED: &str = "<!-- generated by mdboard; do not edit -->";

/// Build `BOARD.md` and `ROADMAP.md` in memory.
#[must_use]
pub fn render_process_views(
    cards: &[ProcessCard],
    policy: &Policy,
    meetings: &[Meeting],
    upstream: Option<&UpstreamRecord>,
    root: &Path,
    roadmap_limit: u32,
) -> RenderPlan {
    let roadmap = cards
        .iter()
        .filter(|card| card.state == State::Roadmap)
        .collect::<Vec<_>>();
    let roadmap_count = roadmap.len();
    let total_tokens: f64 = roadmap
        .iter()
        .filter_map(|card| card.estimate.as_ref())
        .map(|estimate| estimate.tokens.weighted)
        .sum();
    let total_cost = total_tokens / 1_000_000.0 * policy.costs.eur_per_million_tokens;
    let total_cost = if total_cost == 0.0 { 0.0 } else { total_cost };

    let mut board = String::new();
    board.push_str(GENERATED);
    board.push_str("\n\n# Board\n\n");
    board.push_str(&format!(
        "Upstream: `{}` · iteration: {} · roadmap: {} of {} · estimated €{:.4}\n\n",
        policy.branches.upstream,
        upstream.map_or_else(
            || "none".to_owned(),
            |iteration| format!("{} ({:?})", iteration.iteration, iteration.status)
        ),
        roadmap_count,
        roadmap_limit,
        total_cost
    ));
    let active = cards
        .iter()
        .filter(|card| {
            card.kind == mdboard_core::process::Kind::Batch && card.state.is_batch_active()
        })
        .collect::<Vec<_>>();
    if active.is_empty() {
        board.push_str("Active batch: none\n\n");
    } else {
        board.push_str("Active:\n");
        for card in &active {
            board.push_str(&format!(
                "- {} — {} ({})\n",
                card.id, card.title, card.state
            ));
        }
        board.push('\n');
    }
    let pending = meetings
        .iter()
        .filter(|meeting| {
            matches!(
                meeting.status,
                mdboard_core::process::MeetingStatus::Pending
                    | mdboard_core::process::MeetingStatus::Deferred
            )
        })
        .collect::<Vec<_>>();
    if !pending.is_empty() {
        board.push_str("Needs you:\n");
        for meeting in pending {
            board.push_str(&format!("- {} ({:?})\n", meeting.id, meeting.kind));
        }
        board.push('\n');
    }
    board.push_str("## Cards\n\n| ID | Kind | State | Title |\n| --- | --- | --- | --- |\n");
    for card in cards {
        board.push_str(&format!(
            "| {} | {} | {} | {} |\n",
            card.id,
            card.kind,
            card.state,
            card.title.replace('|', "\\|")
        ));
    }

    let mut roadmap_view = String::new();
    roadmap_view.push_str(GENERATED);
    roadmap_view.push_str("\n\n# Roadmap\n\n");
    roadmap_view.push_str(&format!(
        "Limit: {} · committed: {} · estimated total: €{:.4} ({})\n\n",
        roadmap_limit, roadmap_count, total_cost, policy.costs.subscription
    ));
    roadmap_view.push_str(
        "| ID | Title | State | Tokens | Agent hours | Estimated € |\n| --- | --- | --- | ---: | ---: | ---: |\n",
    );
    for card in roadmap {
        let (tokens, hours, cost) = card.estimate.as_ref().map_or((0.0, 0.0, 0.0), |estimate| {
            (
                estimate.tokens.weighted,
                estimate.agent_hours.weighted,
                estimate.tokens.weighted / 1_000_000.0 * policy.costs.eur_per_million_tokens,
            )
        });
        roadmap_view.push_str(&format!(
            "| {} | {} | {} | {tokens:.0} | {hours:.2} | €{cost:.4} |\n",
            card.id,
            card.title.replace('|', "\\|"),
            card.state
        ));
    }

    let mut files = std::collections::BTreeMap::new();
    files.insert(root.join("BOARD.md"), board);
    files.insert(root.join("ROADMAP.md"), roadmap_view);
    RenderPlan { files }
}
