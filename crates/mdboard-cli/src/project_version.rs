//! Project version contract and release update checks.

use std::path::Path;
use std::time::Duration;

use anyhow::{Context, Result, bail};
use mdboard_core::Version;

const DEFAULT_RELEASE_URL: &str =
    "https://raw.githubusercontent.com/mdboard-io/mdboard/release/RELEASE";
const UPDATING_URL: &str = "https://mdboard.io/guide/updating";

#[must_use]
pub fn current() -> Version {
    crate::generated_version::VERSION
        .parse()
        .expect("build-generated VERSION must be valid")
}

pub fn guard(root: &Path) -> Result<()> {
    let Some(project) = project_version(root) else {
        return Ok(());
    };
    let current = current();
    if project.major() > current.major() {
        bail!(
            "this project requires mdboard {project} (major {}), but this binary is {current}; \
             update mdboard before working on it: {UPDATING_URL}#major",
            project.major()
        );
    }
    if project > current {
        eprintln!(
            "mdboard: this project was last used with mdboard {project}; this binary is {current}. \
             Minor and patch differences are safe, but some project features may be unavailable. \
             Update: {UPDATING_URL}"
        );
    }
    Ok(())
}

pub fn ensure_mdboard(root: &Path) -> Result<()> {
    if !root.join("mdboard.toml").is_file() {
        return Ok(());
    }
    let current = current();
    let declared = project_version(root).unwrap_or_else(|| current.clone());
    if declared > current {
        // A lower binary must not claim a project that was created or used by a newer one.
        return Ok(());
    }
    if read_version_file(&root.join("MDBOARD")).is_some_and(|version| version >= current) {
        return Ok(());
    }
    write_mdboard(root)
}

pub fn write_mdboard(root: &Path) -> Result<()> {
    let content = format!(
        "# Generated by mdBoard. Do not edit by hand.\n\
         version = {:?}\n\
         tag = {:?}\n\
         build = {:?}\n\
         commit = {:?}\n\
         updated = {:?}\n",
        crate::generated_version::VERSION,
        crate::generated_version::TAG,
        crate::generated_version::BUILD,
        crate::generated_version::COMMIT,
        crate::generated_version::BUILD_DATE,
    );
    std::fs::write(root.join("MDBOARD"), content)
        .with_context(|| format!("cannot write {}", root.join("MDBOARD").display()))
}

#[must_use]
pub fn release_notice(root: &Path) -> Option<String> {
    if std::env::var_os("MDBOARD_OFFLINE").is_some() {
        return None;
    }
    let local = declared_version(root).unwrap_or_else(current);
    let remote = fetch_release().ok()?;
    if remote <= local {
        return None;
    }
    let (kind, detail) = if remote.major() > local.major() {
        (
            "major",
            "breaking changes; the project must be migrated before the update",
        )
    } else if remote.minor() > local.minor() {
        ("minor", "new features; no breaking changes")
    } else {
        ("patch", "bug fixes; no breaking changes")
    };
    Some(format!(
        "mdboard: a new {kind} version {remote} is available (project uses {local}); {detail}. \
         Update: {UPDATING_URL}#{kind}"
    ))
}

fn declared_version(root: &Path) -> Option<Version> {
    config_version(root).or_else(|| read_version_file(&root.join("MDBOARD")))
}

fn project_version(root: &Path) -> Option<Version> {
    let config = config_version(root);
    let metadata = read_version_file(&root.join("MDBOARD"));
    match (config, metadata) {
        (Some(config), Some(metadata)) => Some(config.max(metadata)),
        (Some(config), None) => Some(config),
        (None, Some(metadata)) => Some(metadata),
        (None, None) => None,
    }
}

fn config_version(root: &Path) -> Option<Version> {
    let text = std::fs::read_to_string(root.join("mdboard.toml")).ok()?;
    let value: toml::Value = toml::from_str(&text).ok()?;
    value.get("mdboard")?.as_str()?.parse().ok()
}

fn read_version_file(path: &Path) -> Option<Version> {
    let text = std::fs::read_to_string(path).ok()?;
    let value: toml::Value = toml::from_str(&text).ok()?;
    value.get("version")?.as_str()?.parse().ok()
}

fn fetch_release() -> Result<Version> {
    if let Ok(path) = std::env::var("MDBOARD_RELEASE_FILE") {
        let text = std::fs::read_to_string(&path)
            .with_context(|| format!("cannot read MDBOARD_RELEASE_FILE {path}"))?;
        return parse_release(&text);
    }
    let url =
        std::env::var("MDBOARD_RELEASE_URL").unwrap_or_else(|_| DEFAULT_RELEASE_URL.to_owned());
    let agent = ureq::AgentBuilder::new()
        .timeout(Duration::from_secs(3))
        .build();
    let response = agent
        .get(&url)
        .call()
        .with_context(|| format!("cannot fetch {url}"))?;
    let text = response
        .into_string()
        .context("cannot read release response")?;
    parse_release(&text)
}

fn parse_release(text: &str) -> Result<Version> {
    let value: toml::Value = toml::from_str(text).context("invalid RELEASE file")?;
    value
        .get("version")
        .and_then(toml::Value::as_str)
        .context("RELEASE has no version")?
        .parse()
        .map_err(|error| anyhow::anyhow!("{error}"))
}
