//! Embed release/build metadata generated from VERSION, BUILD, BUILD_DATE, TAG and Git.

use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let root = manifest.join("../..");
    let makeversion = root.join("sbin/makeversion.sh");
    if !makeversion.is_file() {
        panic!("version script not found: {}", makeversion.display());
    }

    let output = Command::new("bash")
        .arg(&makeversion)
        .current_dir(&root)
        .output()
        .unwrap_or_else(|error| panic!("cannot run {}: {error}", makeversion.display()));
    if !output.status.success() {
        panic!(
            "{} failed:\n{}",
            makeversion.display(),
            String::from_utf8_lossy(&output.stderr)
        );
    }
    let script_output = String::from_utf8_lossy(&output.stdout);
    let version = read_trimmed(&root.join("VERSION"));
    let build = read_trimmed(&root.join("BUILD"));
    let build_date = read_trimmed(&root.join("BUILD_DATE"));
    let tag = read_trimmed(&root.join("TAG"));
    let commit = std::env::var("MDBOARD_COMMIT")
        .ok()
        .filter(|value| !value.trim().is_empty())
        .map(|value| value.chars().take(12).collect())
        .or_else(|| {
            script_output
                .lines()
                .find_map(|line| line.strip_prefix("COMMIT_SHA: "))
                .map(|value| value.chars().take(12).collect())
        })
        .unwrap_or_else(|| "unknown".to_owned());
    let arch = std::env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_else(|_| "unknown".to_owned());
    let tag_suffix = if tag.is_empty() {
        String::new()
    } else {
        format!(".{tag}")
    };
    let display = format!("{version}{tag_suffix}");
    let version_string = format!(
        "{version}-{build}#{}",
        if tag.is_empty() { "none" } else { &tag }
    );

    let source = format!(
        "// generated by crates/mdboard-cli/build.rs; do not edit\n\
         pub const VERSION: &str = {version:?};\n\
         pub const BUILD: &str = {build:?};\n\
         pub const BUILD_DATE: &str = {build_date:?};\n\
         pub const TAG: &str = {tag:?};\n\
         pub const COMMIT: &str = {commit:?};\n\
         pub const ARCH: &str = {arch:?};\n\
         pub const DISPLAY: &str = {display:?};\n\
         pub const TAG_SUFFIX: &str = {tag_suffix:?};\n\
         pub const VERSION_STRING: &str = {version_string:?};\n\
         pub fn banner() -> String {{\n\
             format!(\"mdboard {{DISPLAY}} (build {{BUILD}}, commit {{COMMIT}}, {{BUILD_DATE}})\")\n\
         }}\n\
         pub fn qualified() -> String {{\n\
             format!(\"mdboard{{TAG_SUFFIX}}.{{ARCH}}.{{BUILD}}:{{VERSION}}\")\n\
         }}\n"
    );
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("version.rs");
    std::fs::write(&out, source)
        .unwrap_or_else(|error| panic!("cannot write {}: {error}", out.display()));

    for path in [
        root.join("VERSION"),
        root.join("BUILD"),
        root.join("BUILD_DATE"),
        root.join("TAG"),
        root.join("sbin/makeversion.sh"),
        root.join("sbin/tag.sh"),
    ] {
        println!("cargo:rerun-if-changed={}", path.display());
    }
    println!("cargo:rerun-if-env-changed=MDBOARD_COMMIT");
}

fn read_trimmed(path: &Path) -> String {
    std::fs::read_to_string(path)
        .unwrap_or_else(|error| panic!("cannot read {}: {error}", path.display()))
        .trim()
        .to_owned()
}
